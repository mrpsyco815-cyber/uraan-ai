/**
 * URAAN AI — file generation engine (100% client-side, free).
 * Generates real, valid, downloadable files:
 * PDF (jspdf/MIT), DOCX (docx/MIT), PPTX (pptxgenjs/MIT),
 * XLSX (xlsx/Apache-2.0), CSV, TXT, Markdown, JSON, code files.
 *
 * Every generator validates its output (magic bytes / min size)
 * before returning — no fake download buttons.
 */

export type FileKind = 'pdf' | 'docx' | 'pptx' | 'xlsx' | 'csv' | 'txt' | 'md' | 'json' | 'code'

export interface GeneratedFile {
  kind: FileKind
  filename: string
  mime: string
  blob: Blob
  sizeBytes: number
  /** data URL for preview where supported */
  previewUrl?: string
}

export interface DocSection {
  heading: string
  body: string[] // paragraphs / bullets
}

/** Parse simple markdown into sections for document generators. */
export function parseDocument(md: string): { title: string; sections: DocSection[] } {
  const lines = md.split('\n')
  let title = 'URAAN AI Document'
  const sections: DocSection[] = []
  let current: DocSection | null = null

  for (const raw of lines) {
    const line = raw.trim()
    if (!line) continue
    const h1 = line.match(/^#\s+(.*)/)
    const h2 = line.match(/^##\s+(.*)/)
    if (h1 && title === 'URAAN AI Document') { title = h1[1].trim(); continue }
    if (h2) {
      current = { heading: h2[1].trim(), body: [] }
      sections.push(current)
      continue
    }
    const bullet = line.match(/^[-*]\s+(.*)/)
    const text = bullet ? `• ${bullet[1]}` : line.replace(/\*\*/g, '')
    if (!current) { current = { heading: '', body: [] }; sections.push(current) }
    current.body.push(text)
  }
  if (sections.length === 0) sections.push({ heading: '', body: [md.slice(0, 5000)] })
  return { title, sections }
}

function clean(s: string): string {
  // jspdf's default fonts lack full Unicode; strip unsupported chars gracefully
  return s.replace(/[^\x20-\x7E\u0600-\u06FF\u0750-\u077F\u00A0-\u00FF\u2013\u2014\u2018\u2019\u201C\u201D\u2022\u2026✓✗→←]/g, '')
}

function validate(blob: Blob, magic: string, minBytes: number, kind: string): void {
  if (blob.size < minBytes) {
    throw new Error(`${kind} generation failed: file too small (${blob.size} bytes).`)
  }
  void magic
}

export async function generatePDF(title: string, markdown: string): Promise<GeneratedFile> {
  const { jsPDF } = await import('jspdf')
  const { title: t, sections } = parseDocument(markdown)
  const doc = new jsPDF({ unit: 'mm', format: 'a4' })
  const W = 210, M = 18
  let y = 22

  const ensure = (need: number) => {
    if (y + need > 287) { doc.addPage(); y = 20 }
  }

  // Title page header
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(20)
  doc.setTextColor(6, 59, 70)
  for (const line of doc.splitTextToSize(clean(t || title), W - M * 2)) {
    ensure(10); doc.text(line, M, y); y += 9
  }
  doc.setFontSize(10)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(100, 116, 139)
  ensure(8)
  doc.text(`Generated by URAAN AI — ${new Date().toLocaleDateString('en-GB')}`, M, y)
  y += 4
  doc.setDrawColor(7, 139, 140)
  doc.line(M, y, W - M, y)
  y += 8

  for (const sec of sections) {
    if (sec.heading) {
      doc.setFont('helvetica', 'bold')
      doc.setFontSize(14)
      doc.setTextColor(6, 59, 70)
      ensure(12)
      for (const line of doc.splitTextToSize(clean(sec.heading), W - M * 2)) {
        ensure(8); doc.text(line, M, y); y += 7.5
      }
      y += 2
    }
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(11)
    doc.setTextColor(30, 41, 59)
    for (const para of sec.body) {
      for (const line of doc.splitTextToSize(clean(para), W - M * 2)) {
        ensure(7); doc.text(line, M, y); y += 6
      }
      y += 2.5
    }
    y += 3
  }

  // Footer page numbers
  const pages = doc.getNumberOfPages()
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i)
    doc.setFontSize(9)
    doc.setTextColor(148, 163, 184)
    doc.text(`Page ${i} of ${pages}`, W - M, 292, { align: 'right' })
  }

  const blob = doc.output('blob')
  validate(blob, '%PDF', 1000, 'PDF')
  // Magic-byte check
  const head = new Uint8Array(await blob.slice(0, 5).arrayBuffer())
  const sig = String.fromCharCode(...head)
  if (!sig.startsWith('%PDF')) throw new Error('PDF validation failed: bad header.')
  return {
    kind: 'pdf',
    filename: `${slug(title)}.pdf`,
    mime: 'application/pdf',
    blob, sizeBytes: blob.size,
    previewUrl: URL.createObjectURL(blob),
  }
}

export async function generateDOCX(title: string, markdown: string): Promise<GeneratedFile> {
  const { Document, Packer, Paragraph, TextRun, HeadingLevel } = await import('docx')
  const { title: t, sections } = parseDocument(markdown)
  const children: InstanceType<typeof Paragraph>[] = [
    new Paragraph({ text: t || title, heading: HeadingLevel.TITLE }),
    new Paragraph({
      children: [new TextRun({ text: `Generated by URAAN AI — ${new Date().toLocaleDateString('en-GB')}`, color: '64748B', size: 20 })],
    }),
  ]
  for (const sec of sections) {
    if (sec.heading) children.push(new Paragraph({ text: sec.heading, heading: HeadingLevel.HEADING_1 }))
    for (const para of sec.body) {
      children.push(new Paragraph({ children: [new TextRun({ text: para.replace(/^• /, ''), size: 22 })], bullet: para.startsWith('• ') ? { level: 0 } : undefined }))
    }
  }
  const doc = new Document({ sections: [{ children }] })
  const blob = await Packer.toBlob(doc)
  validate(blob, 'PK', 2000, 'DOCX')
  const head = new Uint8Array(await blob.slice(0, 2).arrayBuffer())
  if (head[0] !== 0x50 || head[1] !== 0x4b) throw new Error('DOCX validation failed: bad ZIP header.')
  return { kind: 'docx', filename: `${slug(title)}.docx`, mime: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', blob, sizeBytes: blob.size }
}

export interface SlideSpec { title: string; bullets: string[] }

export function parseSlides(markdown: string): { title: string; slides: SlideSpec[] } {
  const { title, sections } = parseDocument(markdown)
  const slides: SlideSpec[] = sections.slice(0, 20).map((s) => ({
    title: s.heading || title,
    bullets: s.body.slice(0, 6).map((b) => b.replace(/^• /, '')),
  }))
  if (slides.length === 0) slides.push({ title, bullets: ['Content'] })
  return { title, slides }
}

export async function generatePPTX(title: string, markdown: string): Promise<GeneratedFile> {
  const PptxGenJS = (await import('pptxgenjs')).default
  const { title: t, slides } = parseSlides(markdown)
  const pptx = new PptxGenJS()
  pptx.author = 'URAAN AI'
  pptx.title = t

  // Title slide
  const s0 = pptx.addSlide()
  s0.background = { color: '063B46' }
  s0.addText(t, { x: 0.5, y: 1.8, w: 9, h: 1.5, fontSize: 36, bold: true, color: 'FFFFFF', align: 'center' })
  s0.addText('Generated by URAAN AI', { x: 0.5, y: 3.6, w: 9, h: 0.6, fontSize: 16, color: '16B8AD', align: 'center' })

  for (const s of slides) {
    const slide = pptx.addSlide()
    slide.background = { color: 'FFFFFF' }
    slide.addText(s.title, { x: 0.5, y: 0.3, w: 9, h: 0.8, fontSize: 28, bold: true, color: '063B46' })
    slide.addShape('rect', { x: 0.5, y: 1.05, w: 1.2, h: 0.06, fill: { color: '078B8C' } })
    s.bullets.forEach((b, i) => {
      slide.addText(`•  ${b}`, { x: 0.7, y: 1.4 + i * 0.55, w: 8.6, h: 0.5, fontSize: 16, color: '1E293B' })
    })
    slide.addText('URAAN AI', { x: 8.8, y: 5.1, w: 1, h: 0.3, fontSize: 10, color: '94A3B8', align: 'right' })
  }

  const blob = (await pptx.write({ outputType: 'blob' })) as Blob
  validate(blob, 'PK', 3000, 'PPTX')
  const head = new Uint8Array(await blob.slice(0, 2).arrayBuffer())
  if (head[0] !== 0x50 || head[1] !== 0x4b) throw new Error('PPTX validation failed: bad ZIP header.')
  return { kind: 'pptx', filename: `${slug(title)}.pptx`, mime: 'application/vnd.openxmlformats-officedocument.presentationml.presentation', blob, sizeBytes: blob.size }
}

export async function generateXLSX(title: string, sheets: { name: string; rows: (string | number)[][] }[]): Promise<GeneratedFile> {
  const XLSX = await import('xlsx')
  const wb = XLSX.utils.book_new()
  for (const s of sheets.slice(0, 10)) {
    const ws = XLSX.utils.aoa_to_sheet(s.rows)
    ws['!cols'] = s.rows[0]?.map(() => ({ wch: 22 }))
    XLSX.utils.book_append_sheet(wb, ws, s.name.slice(0, 31))
  }
  const out = XLSX.write(wb, { bookType: 'xlsx', type: 'array' })
  const blob = new Blob([out], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' })
  validate(blob, 'PK', 2000, 'XLSX')
  return { kind: 'xlsx', filename: `${slug(title)}.xlsx`, mime: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', blob, sizeBytes: blob.size }
}

export function generateTextFile(kind: 'csv' | 'txt' | 'md' | 'json' | 'code', title: string, content: string, lang = 'py'): GeneratedFile {
  const exts = { csv: 'csv', txt: 'txt', md: 'md', json: 'json', code: lang }
  const mimes = {
    csv: 'text/csv', txt: 'text/plain', md: 'text/markdown',
    json: 'application/json', code: 'text/plain',
  }
  let body = content
  if (kind === 'json') {
    try { body = JSON.stringify(JSON.parse(content), null, 2) }
    catch { throw new Error('JSON invalid hai — main valid JSON hi generate karunga.') }
  }
  const blob = new Blob([body], { type: `${mimes[kind]};charset=utf-8` })
  if (blob.size < 1) throw new Error('File khaali hai — generate nahi hui.')
  return { kind, filename: `${slug(title)}.${exts[kind]}`, mime: mimes[kind], blob, sizeBytes: blob.size }
}

function slug(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9\u0600-\u06FF]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 50) || 'uraan-document'
}

/** Trigger a real browser download for a generated file. */
export function downloadFile(f: GeneratedFile): void {
  const url = URL.createObjectURL(f.blob)
  const a = document.createElement('a')
  a.href = url
  a.download = f.filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 5000)
}

export function formatBytes(n: number): string {
  if (n < 1024) return `${n} B`
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(1)} KB`
  return `${(n / 1024 / 1024).toFixed(1)} MB`
}
